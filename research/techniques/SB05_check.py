def run_quality(scen, R, seed):
    """Returns (new_errs, b1_errs, b2_errs, b3_errs, burn_frac_new_errs)."""
    events, lins, louts, arrs = gen_stream(scen, R, seed)
    rng = random.Random(seed ^ 0xBEEF)
    ref = RefInfer()
    # baselines
    ewma, ewma_n = 10.0, 0
    b3_s = {}; b3_c = {}
    new_errs, b1_errs, b2_errs, b3_errs, burn_errs = [], [], [], [], []
    fin_count = 0
    burn_limit = 0.2*R
    # walk events; query mid-flight requests at checkpoints synced to the
    # request's physical decode timeline (token/3ms from arr+5ms)
    unfinished = {}
    last_t = 0.0
    for e in events:
        if e[0] == "A":
            _, ln, tt, rid = e
            ref.on_arr(rid, ln, tt-last_t)
            last_t = tt
            unfinished[rid] = [0, ln]
        else:
            _, rid, ft = e
            del unfinished[rid]
            ref.on_fin(rid, lins[rid], louts[rid])
            ewma = 0.05*louts[rid]+0.95*ewma
            ewma_n += 1
            bid = min(lins[rid], MAXLIN)
            b3_s[bid] = b3_s.get(bid, 0.0)+louts[rid]
            b3_c[bid] = b3_c.get(bid, 0)+1
            fin_count += 1
        if unfinished and rng.random() < 0.9:
            rid = rng.choice(list(unfinished.keys()))
            ln = unfinished[rid][1]
            # iter from physical time (tokens produced by now), capped below FIN
            phys = int((last_t - dec_start(arrs, rid)) / 3.0) if last_t > arrs[rid] else 0
            it = max(0, min(louts[rid]-1, phys))
            if it+1 > unfinished[rid][0]:
                ref.on_iter(rid, ln, min(NL, it+1))
                unfinished[rid][0] = min(NL, it+1)
            true_l = louts[rid]
            est = ref.predict_lout(ln, it)
            new_errs.append(est-float(true_l))
            b1 = ewma
            b2 = max(float(ln), ewma)
            bid = min(ln, MAXLIN)
            if b3_c.get(bid, 0) > 0:
                b3 = b3_s[bid]/b3_c[bid]
            else:
                b3 = ewma
            b1_errs.append(b1-float(true_l))
            b2_errs.append(b2-float(true_l))
            b3_errs.append(b3-float(true_l))
            if fin_count <= burn_limit:
                burn_errs.append(est-float(true_l))
    return new_errs, b1_errs, b2_errs, b3_errs, burn_errs


def mse(xs):
    return sum(x*x for x in xs)/len(xs)


def mae(xs):
    return sum(abs(x) for x in xs)/len(xs)


def bias(xs):
    return sum(xs)/len(xs)


