# Check A: equivalence C++ vs reference
# ---------------------------------------------------------------------------

def check_equivalence(verbose=True):
    """C++ vs slow reference on randomized streams incl. mid-flight cut moves."""
    ok = True
    total_events = 0
    for scen in ("heavy", "bimodal", "uniform", "pareto_lin"):
        rng = random.Random(1000+abs(hash(scen)) % 999)
        events, lins, louts, _ = gen_stream(scen, 300, seed=77)
        ref = RefInfer()
        cmds = ["I"]
        exp = []
        last_a = None
        unfinished = {}    # rid -> [cut, lin]
        for e in events:
            for _ in range(3):
                if unfinished and rng.random() < 0.8:
                    rid = rng.choice(list(unfinished.keys()))
                    cut, ln = unfinished[rid]
                    if rng.random() < 0.5 and cut < NL:
                        nc = min(NL, cut + rng.randint(1, 8))
                        ref.on_iter(rid, ln, nc)
                        cmds.append("T %d %d %d" % (rid, ln, nc))
                        unfinished[rid][0] = nc
                        cut = nc
                    it = cut-1
                    cmds.append("Q %d %d" % (ln, it))
                    exp.append(ref.predict_lout(ln, it))
                    if rng.random() < 0.5:
                        cmds.append("V %d %d" % (ln, it))
                        exp.append(ref.predict_sd(ln, it))
            if e[0] == "A":
                _, ln, tt, rid = e
                gap = tt if last_a is None else tt-last_a
                last_a = tt
                ref.on_arr(rid, ln, gap)
                cmds.append("A %d %d %.17g" % (rid, ln, gap))
                unfinished[rid] = [1, ln]
            else:
                _, rid, ft = e
                cur, ln0 = unfinished.pop(rid)
                tgt = min(louts[rid], NL)
                if tgt > cur:
                    ref.on_iter(rid, ln0, tgt)
                    cmds.append("T %d %d %d" % (rid, ln0, tgt))
                ref.on_fin(rid, lins[rid], louts[rid])
                cmds.append("F %d %d %d" % (rid, lins[rid], louts[rid]))
            if rng.random() < 0.3:
                dt = rng.uniform(0.1, 50.0)
                ref.on_decode_ready(dt)
                cmds.append("D %.17g" % dt)
            if rng.random() < 0.25:
                cmds.append("LA"); exp.append(ref.lambda_arr())
                cmds.append("LD"); exp.append(ref.lambda_dr())
                sil = rng.uniform(0.0, 2000.0)
                cmds.append("PA %.17g" % sil); exp.append(ref.p_alive(sil))
                dw = rng.uniform(0.0, 500.0)
                cmds.append("PW %.17g" % dw); exp.append(ref.p_wait_arr(dw))
            if rng.random() < 0.15:
                ids = sorted(unfinished.keys())[:64]
                if ids:
                    cuts = [unfinished[i][0] for i in ids]
                    lns = [unfinished[i][1] for i in ids]
                    cmds.append("Ws %d" % len(ids))
                    for j, i in enumerate(ids):
                        cmds.append("Wj %d %d %d" % (j, cuts[j], lns[j]))
                    cmds.append("We")
                    tw, se = ref.total_work(cuts, lns)
                    exp.append(tw); exp.append(se)
            total_events += 1
        got = cpp_run(cmds)
        if len(got) != len(exp):
            print("FAIL[A %s]: output count %d != expected %d"
                  % (scen, len(got), len(exp)))
            ok = False
            continue
        bad = 0
        firstbad = None
        for idx, (g, x) in enumerate(zip(got, exp)):
            gv = float(g)
            if not close(gv, x):
                bad += 1
                if firstbad is None:
                    firstbad = (idx, g, x)
        if bad:
            print("FAIL[A %s]: %d/%d mismatches; first %r" % (scen, bad, len(exp), firstbad))
            ok = False
        elif verbose:
            print("PASS[A %-11s] %d estimator values bit-matched (<1e-12)"
                  % (scen, len(exp)))
    return ok, total_events


