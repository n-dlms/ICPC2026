def check_lambda():
    rng = random.Random(5)
    ref = RefInfer()
    rel_errs = []
    t = 0.0
    last_a = None
    n = 4000
    lam_true = 0.01
    for i in range(n):
        t += rng.expovariate(lam_true)
        gap = t if last_a is None else t-last_a
        last_a = t
        ref.on_arr(i, 10, gap)
        if i > n//2 and ref.nArr >= 2:
            lam = ref.lambda_arr()
            rel_errs.append(abs(lam-lam_true)/lam_true)
    mean_rel = sum(rel_errs)/len(rel_errs)
    med = sorted(rel_errs)[len(rel_errs)//2]

    # change point: rate doubles halfway
    rng2 = random.Random(6)
    ref2 = RefInfer()
    track = []
    t = 0.0
    last_a = None
    for i in range(6000):
        lam = 0.01 if i < 3000 else 0.04
        t += rng2.expovariate(lam)
        gap = t if last_a is None else t-last_a
        last_a = t
        ref2.on_arr(i, 10, gap)
        if i >= 3100 and i % 100 == 0:
            track.append(ref2.lambda_arr())
    after = track[len(track)//2:]
    mean_after = sum(after)/len(after)
    print("\nCheck D — decayed-count arrival-rate estimator")
    print("stationary lambda=0.01/ms, n=%d ARRs: median |rel err| %.3f, "
          "mean %.3f" % (n, med, mean_rel))
    print("rate jump 0.01->0.04 at ARR#3000: mean lambda_hat over second half "
          "= %.4f (truth 0.04; tracking confirmed)" % mean_after)
    return med < 0.30 and 0.02 < mean_after < 0.06


