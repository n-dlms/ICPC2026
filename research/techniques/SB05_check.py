def check_determinism(runs=3):
    """One fixed ~3,000-event random script (seeded); the driver process is
    re-run from scratch `runs` times; stdout must be byte-identical."""
    rng = random.Random(4242)
    events, lins, louts, _ = gen_stream("bimodal", 1500, seed=99)
    unfinished = {}                     # rid -> current cut
    cmds = ["I"]
    last_a = None
    n_events = 0
    for e in events:
        if unfinished and rng.random() < 0.5:
            rid = rng.choice(sorted(unfinished.keys()))
            cut, ln = unfinished[rid], lins[rid]
            if rng.random() < 0.5 and cut < NL:
                nc = min(NL, cut + rng.randint(1, 8))
                cmds.append("T %d %d %d" % (rid, ln, nc))
                unfinished[rid] = nc
                cut = nc
            if rng.random() < 0.5:
                cmds.append("Q %d %d" % (ln, cut - 1))
            if rng.random() < 0.3:
                cmds.append("V %d %d" % (ln, cut - 1))
        if e[0] == "A":
            _, ln, tt, rid = e
            gap = tt if last_a is None else tt - last_a
            last_a = tt
            cmds.append("A %d %d %.17g" % (rid, ln, gap))
            cmds.append("D %.17g" % max(1e-3, gap / 3.0))
            unfinished[rid] = 1
            n_events += 1
        else:
            _, rid, ft = e
            cmds.append("F %d %d %d" % (rid, lins[rid], louts[rid]))
            unfinished.pop(rid, None)
            n_events += 1
        if n_events % 250 == 0:
            cmds += ["LA", "LD", "PA %.17g" % rng.uniform(1.0, 2000.0),
                     "PW %.17g" % rng.uniform(1.0, 500.0)]
    # one total_work block (exercises the Ws/Wj/We driver path)
    mem = [(rid, cut, lins[rid]) for rid, cut in list(unfinished.items())[:8]]
    cmds.append("Ws %d" % len(mem))
    for j, (rid, cut, ln) in enumerate(mem):
        cmds.append("Wj %d %d %d" % (j, cut, ln))
    cmds.append("We")
    inp = "\n".join(cmds) + "\nX\n"
    outs = []
    for _ in range(runs):
        r = subprocess.run([DRIVER], input=inp, capture_output=True, text=True)
        if r.returncode != 0:
            print("FAIL[G]: driver exit %d: %s" % (r.returncode, r.stderr))
            return False
        outs.append(r.stdout)
    ok = len(set(outs)) == 1
    print("\nCheck G — determinism: %d fresh driver runs on a %d-event script: %s"
          % (runs, n_events, "byte-identical stdout" if ok else "DIVERGED"))
    return ok


