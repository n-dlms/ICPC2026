# ---------------------------------------------------------------------------

def check_p_alive():
    """Decisive separation on low-variance gap streams + recovery after lull."""
    rng = random.Random(11)

    def feed(gaps):
        ref = RefInfer()
        for i, g in enumerate(gaps):
            ref.on_arr(i, 10, g)
        return ref

    # (a) deterministic-ish gaps U[9,11] ms: a 200ms silence is decisive
    gaps_u = [rng.uniform(9.0, 11.0) for _ in range(800)]
    med_u = sorted(gaps_u)[len(gaps_u)//2]
    r_end = feed(gaps_u)
    p_after_10x = r_end.p_alive(200.0)      # ~20x median silence, stream ended

    # (b) same stream mid-run: silence equal to the largest plausible gap is
    # NOT decisive while the process is alive -> p_alive must stay high at
    # silences within the observed support.
    p_within = r_end.p_alive(med_u)

    # (c) heavy-tail stream (exponential): 10x-median silence is genuinely
    # ambiguous under the model; posterior may stay moderate — document only.
    gaps_x = [rng.expovariate(0.05) for _ in range(1500)]
    med_x = sorted(gaps_x)[len(gaps_x)//2]
    r_x = feed(gaps_x)
    p_x_10x = r_x.p_alive(10*med_x)
    p_x_within = r_x.p_alive(med_x)

    # (d) recovery: resume the ended uniform stream, posterior climbs back
    r_rec = feed(gaps_u)
    before = r_rec.p_alive(200.0)
    r_rec.on_arr(800, 10, 200.0)
    after = r_rec.p_alive(med_u)

    print("\nCheck E — lull-vs-ended posterior P(alive|silence)")
    print("uniform gaps U[9,11]: p_alive(1x median)=%.3f (should stay high), "
          "p_alive(20x median after end)=%.3f (should be low)"
          % (p_within, p_after_10x))
    print("exponential gaps: p_alive(1x median)=%.3f, p_alive(10x median "
          "after end)=%.3f (ambiguity is model-correct)" % (p_x_within, p_x_10x))
    print("recovery after one resumed arrival: %.3f -> %.3f" % (before, after))
    ok = p_within > 0.9 and p_after_10x < 0.5 and after > before
    return ok


