def draw_lout(scenario, lin, rng):
    if scenario == "heavy":
        mu = math.log(6.0) + 0.35*math.log(lin)
        v = rng.lognormvariate(mu - 0.36, 1.1)
        return max(1, min(512, int(round(v))))
    if scenario == "bimodal":
        if rng.random() < 0.7:
            return rng.randint(1, 3)
        return rng.randint(96, 512)
    if scenario == "uniform":
        return rng.randint(1, 512)
    if scenario == "pareto_lin":
        base = (lin/256.0)**1.5*rng.expovariate(1.0)
        return max(1, min(512, int(round(base))+1))
    raise ValueError(scenario)


def gen_stream(scenario, R, seed):
    """Returns event list [('A',lin,t) ('D',t) ('F',rid,t)] and request table."""
    rng = random.Random(seed)
    lins, louts, arrs = [], [], []
    t = 0.0
    for i in range(R):
        # inter-arrival: mixture of quiet and busy phases (nonstationary)
        lam = 0.02 if (i // 250) % 2 == 0 else 0.2
        t += rng.expovariate(lam)
        lin = max(1, min(4096, int(rng.lognormvariate(5.0, 1.3))))
        lins.append(lin)
        louts.append(draw_lout(scenario, lin, rng))
        arrs.append(t)
    # abstract service: prefill 5 ms + Lout tokens x 3 ms -> FIN times;
    # merge into ONE time-sorted event stream (ARR before FIN at ties)
    fins = [(arrs[i]+5.0+louts[i]*3.0, i) for i in range(R)]
    fins.sort()
    ev = []
    ai = 0
    for ft, i in fins:
        while ai < R and arrs[ai] <= ft:
            ev.append(("A", lins[ai], arrs[ai], ai))
            ai += 1
        ev.append(("F", i, ft))
    while ai < R:
        ev.append(("A", lins[ai], arrs[ai], ai))
        ai += 1
    return ev, lins, louts, arrs


