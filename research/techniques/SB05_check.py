#!/usr/bin/env python3
"""SB05 check — validates sb05::Infer (SB05_inference.cpp) against independent
slow Python references on synthetic streams (>= 1e5 events total).

Checks
  A. reference equivalence : C++ vs slow Python re-implementation on randomized
     event streams (floats |rel|<1e-12; integers exact).
  B. Lout posterior quality: MSE/MAE of predict_lout vs TRUE Lout at survival-
     conditioned query points, vs baselines (plain EWMA / max(Lin,ewma) /
     per-exact-Lin-bucket mean = the deployed D-151 path).
  C. total_work            : exactness vs brute force + Gaussian CI coverage.
  D. arrival rate          : lambda_hat accuracy on stationary + change-point
     Poisson streams.
  E. lull-vs-ended         : p_alive separation between hard stream end and a
     long mid-stream lull at matched silences.
  F. endgame trigger       : hold_dpre vs closed-form recomputation.
  G. determinism           : identical driver stdout across repeated runs.

No repository judging/scoring tooling is used anywhere: every "true" value is
generated by this script's own simulators.
"""
import math
import random
import subprocess
import sys

DRIVER = "/tmp/sb05_driver"

# ---------------------------------------------------------------------------
# Slow reference implementation — mirrors sb05::Infer operation-for-operation.
# ---------------------------------------------------------------------------
NL = 512
LG = NL + 1
NB = 24
NROW = NB + 1
MAXLIN = 4096
PRIOR_LOUT = 10.0
KAPPA = 4.0
GAPB = 32
GAMMA = 0.98
PI_DEAD = 0.02

EDGES = [1,2,3,4,6,8,11,16,23,32,45,64,91,128,
         181,256,362,512,724,1024,1448,2048,2896,4096,MAXLIN+1]


class RefInfer:
    def __init__(self):
        self.lin2b = [0]*(MAXLIN+1)
        b = 0
        for l in range(1, MAXLIN+1):
            while l >= EDGES[b+1]:
                b += 1
            self.lin2b[l] = b
        self.cSuf = [[0]*LG for _ in range(NROW)]
        self.sSuf = [[0.0]*LG for _ in range(NROW)]
        self.qSuf = [[0.0]*LG for _ in range(NROW)]
        self.tCnt = [0]*NROW
        self.tSum = [0.0]*NROW
        self.tSum2 = [0.0]*NROW
        self.RMAX = 2000
        self.aCut = [0]*self.RMAX
        self.aVal = [0.0]*self.RMAX
        self.aOn = [0]*self.RMAX
        self.eCnt = [[0]*LG for _ in range(NROW)]
        self.eSum = [[0.0]*LG for _ in range(NROW)]
        self.eSum2 = [[0.0]*LG for _ in range(NROW)]
        self.ewma_lout = PRIOR_LOUT
        self.ewma_n = 0
        self.fin_count = 0
        self.aArr = 0.0; self.gArr = 0.0; self.nArr = 0
        self.aDr = 0.0; self.gDr = 0.0; self.nDr = 0
        self.uSuf = [0.0]*GAPB
        self.uTot = 0.0

    @staticmethod
    def gap_bin(g):
        if not (g > 1.0):
            return 0
        lg = math.log10(g)*4.0
        if lg >= GAPB:
            return GAPB-1
        k = int(lg)
        if k < 0:
            k = 0
        return k

    def clamp_lin(self, lin):
        return 1 if lin < 1 else (MAXLIN if lin > MAXLIN else lin)

    def on_arr(self, rid, lin, gap_ms):
        self.nArr += 1
        if 0 <= rid < self.RMAX and not self.aOn[rid]:
            self.inject(rid, lin, 1)
        self.aArr = self.aArr*GAMMA + 1.0
        self.gArr = gap_ms if self.nArr == 1 else \
            self.gArr*GAMMA + (1.0-GAMMA)*gap_ms
        if self.nArr >= 2 and gap_ms >= 0.0:
            k = self.gap_bin(gap_ms)
            for j in range(k+1):
                self.uSuf[j] += 1.0
            self.uTot += 1.0

    def on_decode_ready(self, gap_ms):
        self.nDr += 1
        self.aDr = self.aDr*GAMMA + 1.0
        self.gDr = gap_ms if self.nDr == 1 else \
            self.gDr*GAMMA + (1.0-GAMMA)*gap_ms

    def suffC(self, row, c):
        ncomp = self.cSuf[row][c]
        n = self.eCnt[row][c]
        n = n if n > 0 else 0
        if n > 0:
            mean = self.eSum[row][c]/float(n)
            if ncomp > 0:
                mc = self.sSuf[row][c]/float(ncomp)
                vc = self.qSuf[row][c]/float(ncomp) - mc*mc
                var = vc if vc > 0.0 else 0.0
            else:
                var = 0.0
            hi = float(NL) - (mean if mean > float(c) else float(c))
            h2 = hi if hi > 1.0 else 1.0
            fl = h2*h2/12.0
            wnc = float(ncomp)/(float(ncomp)+float(self.N0))
            var = wnc*var + (1.0-wnc)*fl
            return n, mean, var, ncomp
        return 0, 0.0, 0.0, 0

    @staticmethod
    def suffR(cs, ss, row, c):
        n = cs[row][c]
        mean = ss[row][c]/float(n) if n > 0 else 0.0
        return n, mean

    def t_glob(self, c):
        if c < 1:
            c = 1
        if c > NL:
            c = NL
        gn, gm = self.suffR(self.cSuf, self.sSuf, NB, c)
        if gn > 0:
            return gm
        rn, rm, rs = self.mom(NB)
        if rn > 0:
            sd = rs if rs >= 1.0 else 1.0
            z = (float(c)-rm)/sd
            est = rm + sd*self.mills(z)
            return est if est >= float(c) else float(c)
        if self.ewma_n > 0:
            est = self.ewma_lout if self.ewma_lout >= float(c) else float(c)
            return est
        p = PRIOR_LOUT if PRIOR_LOUT >= float(c) else float(c)
        return p

    def inject_add(self, r, c, v):
        for l in range(1, c+1):
            self.eCnt[r][l] += 1
            self.eSum[r][l] += v
            self.eSum2[r][l] += v*v

    def inject_remove(self, rid, r):
        c = self.aCut[rid]
        v = self.aVal[rid]
        for l in range(1, c+1):
            self.eCnt[r][l] -= 1
            self.eSum[r][l] -= v
            self.eSum2[r][l] -= v*v
        self.aOn[rid] = 0

    def inject(self, rid, lin, cut):
        if not (0 <= rid < self.RMAX):
            return
        if cut < 1:
            cut = 1
        if cut > NL:
            cut = NL
        r = self.lin2b[self.clamp_lin(lin)]
        if self.aOn[rid]:
            self.inject_remove(rid, r)
        v = self.t_glob(cut)
        self.aCut[rid] = cut
        self.aVal[rid] = v
        self.aOn[rid] = 1
        self.inject_add(r, cut, v)
        self.inject_add(NB, cut, v)

    def on_iter(self, rid, lin, nc):
        if nc > NL:
            nc = NL
        self.inject(rid, lin, nc)

    def on_fin(self, rid, lin, lout):
        if lout < 1:
            lout = 1
        if lout > NL:
            lout = NL
        r = self.lin2b[self.clamp_lin(lin)]
        if 0 <= rid < self.RMAX and self.aOn[rid]:
            self.inject_remove(rid, r)
        for c in range(1, lout+1):
            self.cSuf[r][c] += 1
            self.sSuf[r][c] += float(lout)
            self.qSuf[r][c] += float(lout)*float(lout)
            self.cSuf[NB][c] += 1
            self.sSuf[NB][c] += float(lout)
            self.qSuf[NB][c] += float(lout)*float(lout)
        self.fin_count += 1
        self.tCnt[r] += 1; self.tSum[r] += float(lout)
        self.tSum2[r] += float(lout)*float(lout)
        self.tCnt[NB] += 1; self.tSum[NB] += float(lout)
        self.tSum2[NB] += float(lout)*float(lout)
        self.ewma_lout = 0.05*float(lout) + 0.95*self.ewma_lout
        self.ewma_n += 1

    @staticmethod
    def suff(cs, ss, qs, row, c):
        n = cs[row][c]
        if n > 0:
            mean = ss[row][c]/float(n)
            var = qs[row][c]/float(n) - mean*mean
            if var < 0.0:
                var = 0.0
            return n, mean, var
        return 0, 0.0, 0.0

    def mom(self, row):
        n = self.tCnt[row]
        if n > 0:
            mu = self.tSum[row]/float(n)
            v = self.tSum2[row]/float(n) - mu*mu
            if v < 0.0:
                v = 0.0
            return n, mu, math.sqrt(v)
        return 0, 0.0, 0.0

    @staticmethod
    def mills(z):
        if z > 8.0:
            return z + 1.0/z
        if z < -8.0:
            z = -8.0
        return math.exp(-0.5*z*z)*0.7978845608028654/math.erfc(z*0.70710678118654752)

    N0 = 20

    def sd_eff(self, sd, n, c, mu):
        hi = float(NL) - (mu if mu > c else c)
        if hi < 1.0:
            hi = 1.0
        w = n/(n + float(self.N0))
        return math.sqrt(w*sd*sd + (1.0-w)*hi*hi/12.0)

    def var_floor(self, var, n, c, mean):
        return self.sd_eff(math.sqrt(var if var > 0.0 else 0.0), n, c, mean)

    def predict_lout(self, lin, iter_):
        c = iter_ + 1
        if c < 1:
            c = 1
        if c > NL:
            c = NL
        r = self.lin2b[self.clamp_lin(lin)]
        bn, bm, _, _ = self.suffC(r, c)
        gn, gm, _, _ = self.suffC(NB, c)
        if bn > 0 or gn > 0:
            nb = float(bn); ng = float(gn)
            w = nb/(nb + ng + KAPPA)
            mb = bm if bn > 0 else gm
            mg = gm if gn > 0 else mb
            est = w*mb + ((ng + KAPPA)/(nb + ng + KAPPA))*mg
        else:
            rn, rm, rs = self.mom(r)
            gn2, gm2, gs2 = self.mom(NB)
            if rn > 0 or gn2 > 0:
                nb = float(rn); ng = float(gn2)
                w = nb/(nb + ng + KAPPA)
                mu = w*(rm if rn > 0 else gm2) + \
                     ((ng + KAPPA)/(nb + ng + KAPPA))*(gm2 if gn2 > 0 else rm)
                sg = gs2 if gn2 > 0 else rs
                sb = rs if rn > 0 else sg
                sd = w*sb + (1.0-w)*sg
                nn = w*float(rn) + (1.0-w)*float(gn2)
                s2 = self.sd_eff(sd, nn, float(c), mu)
                z = (float(c) - mu)/s2
                est = mu + s2*self.mills(z)
            elif self.ewma_n > 0:
                est = self.ewma_lout
            else:
                est = PRIOR_LOUT
        cc = float(c)
        return est if est >= cc else cc

    def predict_sd(self, lin, iter_):
        c = iter_ + 1
        if c < 1:
            c = 1
        if c > NL:
            c = NL
        r = self.lin2b[self.clamp_lin(lin)]
        bn, bm, bv, _ = self.suffC(r, c)
        gn, gm, gv, _ = self.suffC(NB, c)
        if bn > 0 or gn > 0:
            nb = float(bn); ng = float(gn)
            w = nb/(nb + ng + KAPPA)
            vb = bv if bn > 0 else gv
            vg = gv if gn > 0 else vb
            mb = bm if bn > 0 else gm
            mg = gm if gn > 0 else mb
            d = mg - mb if mg >= mb else mb - mg
            v = w*vb + (1.0-w)*vg + w*(1.0-w)*d*d
            nn2 = w*float(bn) + (1.0-w)*float(gn)
            mu2 = bm if bn > 0 else gm
            return self.var_floor(v, nn2, float(c), mu2)
        rn, rm, rs = self.mom(r)
        gn2, gm2, gs2 = self.mom(NB)
        if rn > 0 or gn2 > 0:
            nb = float(rn); ng = float(gn2)
            w = nb/(nb + ng + KAPPA)
            mu = w*(rm if rn > 0 else gm2) + \
                 ((ng + KAPPA)/(nb + ng + KAPPA))*(gm2 if gn2 > 0 else rm)
            sg = gs2 if gn2 > 0 else rs
            sb = rs if rn > 0 else sg
            sd = w*sb + (1.0-w)*sg
            nn = w*float(rn) + (1.0-w)*float(gn2)
            s2 = self.sd_eff(sd, nn, float(c), mu)
            z = (float(c) - mu)/s2
            mi = self.mills(z)
            vt = s2*s2*(1.0 + z*mi - mi*mi)
            return math.sqrt(vt if vt > 0.0 else s2)
        if self.ewma_n > 0:
            d = self.ewma_lout if self.ewma_lout >= PRIOR_LOUT else PRIOR_LOUT
            return 0.6*d
        return 0.6*PRIOR_LOUT

    def total_work(self, cuts, lins):
        tot = 0.0
        var = 0.0
        for j in range(len(cuts)):
            c = cuts[j]
            if c < 1:
                c = 1
            mu = self.predict_lout(lins[j], c-1)
            rem = mu - float(c-1)
            if rem < 1.0:
                rem = 1.0
            tot += rem
            r = self.lin2b[self.clamp_lin(lins[j])]
            bn, bmn, bv, _ = self.suffC(r, c)
            gn, gmn, gv, _ = self.suffC(NB, c)
            if bn > 0 or gn > 0:
                nb = float(bn); ng = float(gn)
                w = nb/(nb + ng + KAPPA)
                vb = bv if bn > 0 else gv
                vg = gv if gn > 0 else vb
                mb = bmn if bn > 0 else gmn
                mg = gmn if gn > 0 else bmn
                dm = mg - mb if mg >= mb else mb - mg
                vv = w*vb + (1.0-w)*vg + w*(1.0-w)*dm*dm
                nn2 = w*float(bn) + (1.0-w)*float(gn)
                mu2 = bmn if bn > 0 else gmn
                v = self.var_floor(vv, nn2, float(c), mu2)**2
                npar = vb if bn > 0 else (gv if gn > 0 else v)
            else:
                rn, _, rs = self.mom(r)
                gn3, _, gs3 = self.mom(NB)
                cc = float(c)
                if rn > 0 or gn3 > 0:
                    w = float(rn)/(float(rn)+float(gn3)+KAPPA)
                    sg = gs3 if gn3 > 0 else rs
                    sb = rs if rn > 0 else sg
                    sd = w*sb + (1.0-w)*sg
                    nn = w*float(rn) + (1.0-w)*float(gn3)
                    mu2 = mu if mu > cc else cc
                    v = self.sd_eff(sd, nn, cc, mu2)**2
                    npar = v
                else:
                    d = self.ewma_lout if self.ewma_n > 0 else PRIOR_LOUT
                    mu3 = mu if mu > cc else cc
                    v = self.sd_eff(0.6*d, float(self.ewma_n), cc, mu3)**2
                    npar = v
            var += v
            nbk = bn if bn > 0 else (gn if gn > 0 else (self.tCnt[r] if self.tCnt[r] > 0 else 1))
            var += npar/float(nbk)
        return tot, math.sqrt(var if var > 0.0 else 0.0)

    def lambda_arr(self):
        if self.nArr < 2 or not (self.gArr > 0.0):
            return 0.0
        return (self.aArr*(1.0-GAMMA)/GAMMA)/self.gArr

    def lambda_dr(self):
        if self.nDr < 2 or not (self.gDr > 0.0):
            return 0.0
        return (self.aDr*(1.0-GAMMA)/GAMMA)/self.gDr

    def p_wait_arr(self, delta):
        lam = self.lambda_arr()
        if lam <= 0.0:
            return 1.0
        alpha = self.aArr/(1.0-GAMMA)
        beta = alpha/lam
        r = beta/(beta + (delta if delta > 0.0 else 0.0))
        return r**alpha

    def p_alive(self, silence_ms):
        if self.nArr < 2:
            return 1.0
        k = self.gap_bin(silence_ms if silence_ms > 0.0 else 0.0)
        sh = (self.uSuf[k]+1.0)/(self.uTot+2.0)
        alive = (1.0-PI_DEAD)*sh
        return alive/(PI_DEAD+alive)

    def r_hat(self, arrived, horizon_ms):
        extra = self.lambda_arr()*(horizon_ms if horizon_ms > 0.0 else 0.0)
        return float(arrived)+extra


def hold_dpre(p_al, lam_dr, C1, p_crit, n_mt, rho_S):
    return p_al*lam_dr*C1 > p_crit + rho_S*n_mt


# ---------------------------------------------------------------------------
# C++ driver harness
# ---------------------------------------------------------------------------

def cpp_run(cmd_lines):
    inp = "\n".join(cmd_lines)+"\nX\n"
    out = subprocess.run([DRIVER], input=inp, capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError("driver failed: %s" % out.stderr)
    return out.stdout.split()


def close(a, b, tol=1e-12):
    if a == b:
        return True
    d = abs(a-b)
    return d <= tol*max(1.0, abs(a), abs(b))


